#!/usr/bin/env python3
"""Embed notes/NN.md into v33-features.html so the presenter window works
without a server (file://) as well as on GitHub Pages.

Usage: python3 build-notes.py [html] [notes_dir]
The md files stay the source of truth; run this after editing them.
"""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parent
html_path = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'v33-features.html'
notes_dir = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else root / 'notes'

BEGIN, END = '<!-- notes:begin (generated by build-notes.py) -->', '<!-- notes:end -->'

notes = {p.stem: p.read_text(encoding='utf-8') for p in sorted(notes_dir.glob('[0-9][0-9].md'))}
payload = json.dumps(notes, ensure_ascii=False, indent=0).replace('</', '<\\/')
block = f'{BEGIN}\n<script id="notes-data" type="application/json">\n{payload}\n</script>\n{END}'

html = html_path.read_text(encoding='utf-8')
pattern = re.compile(re.escape(BEGIN) + r'.*?' + re.escape(END), re.S)
if pattern.search(html):
    html = pattern.sub(lambda _: block, html)
else:
    # first run: put the block right before the main script
    html = html.replace('\n<script>', f'\n{block}\n<script>', 1)
html_path.write_text(html, encoding='utf-8')

slides = len(re.findall(r'<section class="slide', html))
missing = [f'{i:02d}' for i in range(1, slides + 1) if f'{i:02d}' not in notes]
print(f'{len(notes)} notes embedded into {html_path.name} ({slides} slides)')
if missing:
    print('missing: ' + ', '.join(f'notes/{m}.md' for m in missing))
